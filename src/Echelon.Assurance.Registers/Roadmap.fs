/// Render the generated controls-by-phase roadmap view from the catalog. Pure.
module Echelon.Assurance.Registers.Roadmap

let phases =
    [
        "P0", "Requirements reconciliation"
        "P1", "Shared foundations"
        "P2", "Unbound reference implementation"
        "P3", "Operational readiness"
        "P4", "External assurance readiness"
        "P5", "Organizational scale"
    ]
    |> Map.ofList

let render (controls: Map<string, string> list) : string =
    let section (phase: string, rows: Map<string, string> list) =
        let rows =
            rows
            |> List.sortWith (fun a b -> System.String.CompareOrdinal(a["control_id"], b["control_id"]))

        let body =
            rows
            |> List.map (fun c ->
                sprintf
                    "| %s | %s | %s | %s | %s |"
                    c["control_id"]
                    c["title"]
                    c["automation_target"]
                    c["failure_mode"]
                    c["owner_role"])

        [
            sprintf "## %s — %s (%d controls)" phase phases[phase] (List.length rows)
            ""
            "| Control | Title | Target | Failure mode | Owner |"
            "|---|---|---|---|---|"
        ]
        @ body
        @ [ "" ]
        |> String.concat "\n"

    let header =
        "# Controls by roadmap phase (generated)\n\n"
        + "Generated by `assurance roadmap` (src/Echelon.Assurance.Cli) from `controls/control-catalog.csv`. Do not edit by hand.\n\n"

    let sections =
        controls
        |> List.groupBy (fun c -> c["roadmap_phase"])
        |> List.sortBy fst
        |> List.map section

    header + String.concat "\n" sections

/// Render the cross-repository backlog grouped by phase (dependency order is
/// enforced by the validator).
let renderBacklog (items: Map<string, string> list) : string =
    let section (phase: string, rows: Map<string, string> list) =
        [
            sprintf "## %s — %s (%d work items)" phase phases[phase] (List.length rows)
            ""
            "| Work item | Repository | Title | Requirements | Depends on | Effort | Blockers |"
            "|---|---|---|---|---|---|---|"
        ]
        @ (rows
           |> List.map (fun w ->
               sprintf
                   "| %s | %s | %s | %s | %s | %s | %s |"
                   w["work_item_id"]
                   w["repository"]
                   w["title"]
                   (w["requirements_addressed"].Replace(";", ", "))
                   (w["dependencies"].Replace(";", ", "))
                   w["effort"]
                   (w["blockers"].Replace(";", ", "))))
        @ [ "" ]
        |> String.concat "\n"

    "# Implementation backlog by phase (generated)\n\n"
    + "Generated by `assurance roadmap` from `roadmap/backlog.csv`. Do not edit by hand. "
    + "Every item is `proposed`: this initiative authorizes specifications and backlog items, not implementation. "
    + "Items in other repositories are proposals for those repositories; nothing was changed there.\n\n"
    + (items
       |> List.groupBy (fun w -> w["phase"])
       |> List.sortBy fst
       |> List.map section
       |> String.concat "\n")
