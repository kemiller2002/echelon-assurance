/// Five-year total cost of ownership model. Pure.
/// Input rows: scenario, component, category, y1_low, y1_high, annual_low,
/// annual_high, avoidable ("no" = unavoidable external cost), evidence_class,
/// source_ids, notes. Ranges are carried as low/high, never collapsed.
module Echelon.Assurance.Registers.Tco

let years = 5

type Line =
    {
        Scenario: string
        Avoidable: string
        Y1: float * float
        Annual: float * float
    }

type Totals =
    {
        Unavoidable: float * float
        Reducible: float * float
    }

let private number (s: string) = if s.Trim() = "" then 0.0 else float s

let line (record: Map<string, string>) =
    {
        Scenario = record["scenario"]
        Avoidable = record["avoidable"]
        Y1 = number record["y1_low"], number record["y1_high"]
        Annual = number record["annual_low"], number record["annual_high"]
    }

let discount rate year =
    1.0 / ((1.0 + rate) ** float (year - 1))

let fiveYear rate (l: Line) =
    let later = [ 2..years ] |> List.sumBy (discount rate)
    fst l.Y1 + fst l.Annual * later, snd l.Y1 + snd l.Annual * later

let private add (a: float * float) (b: float * float) = fst a + fst b, snd a + snd b

let summarise rate (lines: Line list) : (string * Totals) list =
    lines
    |> List.groupBy (fun l -> l.Scenario)
    |> List.sortWith (fun (a, _) (b, _) -> System.String.CompareOrdinal(a, b))
    |> List.map (fun (scenario, ls) ->
        let total pred =
            ls |> List.filter pred |> List.map (fiveYear rate) |> List.fold add (0.0, 0.0)

        scenario,
        {
            Unavoidable = total (fun l -> l.Avoidable = "no")
            Reducible = total (fun l -> l.Avoidable = "yes")
        })

let private money (v: float) =
    "$"
    + (System.Math.Round(v, System.MidpointRounding.ToEven))
        .ToString("#,0", System.Globalization.CultureInfo.InvariantCulture)

let private range (lo, hi) = sprintf "%s – %s" (money lo) (money hi)

let renderMarkdown rate (totals: (string * Totals) list) =
    let row (s, t) =
        sprintf
            "| %s | %s | %s | %s |"
            s
            (range t.Unavoidable)
            (range t.Reducible)
            (range (add t.Unavoidable t.Reducible))

    [
        "# Five-year TCO summary (generated)"
        ""
        sprintf
            "Generated by `assurance tco` from `economics/parameters.csv`. Discount rate: %s."
            ((rate * 100.0).ToString("0", System.Globalization.CultureInfo.InvariantCulture)
             + "%")
        "Do not edit by hand. Ranges, not point estimates. See `economics/compliance-economics.md` for interpretation."
        ""
        "> **Superseded (v1, preserved for comparison).** Owner direction DF-ASR-2026-0D0F replaced the assumptions behind the 'external under v1 assumptions' column (contracted reviewer, external testing, assumed auditor reliance). Use `economics/v2/` (S8–S12) for current planning."
        ""
        "| Scenario | External under v1 assumptions | Reducible | Total (5 yr) |"
        "|---|---|---|---|"
    ]
    @ (totals |> List.map row)
    |> String.concat "\n"
    |> fun s -> s + "\n"

let renderCsv (totals: (string * Totals) list) : Csv.Row list =
    let r (v: float) =
        string (int64 (System.Math.Round(v, System.MidpointRounding.ToEven)))

    [
        "scenario"
        "unavoidable_low"
        "unavoidable_high"
        "reducible_low"
        "reducible_high"
    ]
    :: (totals
        |> List.map (fun (s, t) ->
            [
                s
                r (fst t.Unavoidable)
                r (snd t.Unavoidable)
                r (fst t.Reducible)
                r (snd t.Reducible)
            ]))
