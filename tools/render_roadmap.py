#!/usr/bin/env python3
"""Render roadmap/generated/controls-by-phase.md from the control catalog.

Pure rendering from controls/control-catalog.csv; I/O only in main.
"""

import csv
import sys
from itertools import groupby
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PHASES = {
    "P0": "Immediate organizational requirements",
    "P1": "Required before production",
    "P2": "Required before onboarding financial institutions",
    "P3": "Required before beginning an audit observation period",
    "P4": "Required for external attestation",
    "P5": "Longer-term improvements",
}


def render(controls) -> str:
    ordered = sorted(controls, key=lambda c: (c["roadmap_phase"], c["control_id"]))

    def section(phase, rows):
        rows = tuple(rows)
        body = (
            f"| {c['control_id']} | {c['title']} | {c['automation_target']} | {c['failure_mode']} | {c['owner_role']} |"
            for c in rows
        )
        return "\n".join((
            f"## {phase} — {PHASES[phase]} ({len(rows)} controls)", "",
            "| Control | Title | Target | Failure mode | Owner |", "|---|---|---|---|---|", *body, "",
        ))

    sections = (section(p, rows) for p, rows in groupby(ordered, key=lambda c: c["roadmap_phase"]))
    header = ("# Controls by roadmap phase (generated)\n\n"
              "Generated by `tools/render_roadmap.py` from `controls/control-catalog.csv`. Do not edit by hand.\n\n")
    return header + "\n".join(sections)


def main() -> int:
    with (ROOT / "controls/control-catalog.csv").open(newline="", encoding="utf-8") as h:
        controls = tuple(csv.DictReader(h))
    out = ROOT / "roadmap/generated"
    out.mkdir(parents=True, exist_ok=True)
    (out / "controls-by-phase.md").write_text(render(controls), encoding="utf-8")
    print(f"rendered {len(controls)} controls")
    return 0


if __name__ == "__main__":
    sys.exit(main())
