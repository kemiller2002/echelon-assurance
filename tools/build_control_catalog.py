def read(path: Path):
    with path.open(newline="", encoding="utf-8") as h:
        return list(csv.DictReader(h))


def write(path: Path, cols, rows) -> None:
    with path.open("w", newline="", encoding="utf-8") as h:
        w = csv.DictWriter(h, fieldnames=cols, lineterminator="\n")
        w.writeheader()
        w.writerows(rows)


def sources_for(reqs, req_index) -> str:
    srcs = sorted({s for r in reqs for s in req_index.get(r, {}).get("source_ids", "").split(";") if s})
    return J(srcs)


def reverse(controls, field: str) -> dict:
    out = {}
    for c in controls:
        for key in filter(None, c[field].split(";")):
            out.setdefault(key, []).append(c["control_id"])
    return out


def relink(path: Path, spec_name: str, id_col: str, mapping: dict, policy_parent: bool = False) -> None:
    rows = read(path)
    cols = REGISTERS[spec_name]["columns"]

    def ids_for(r):
        own = mapping.get(r[id_col], [])
        return J(sorted(set(own)))

    write(path, cols, [{**r, "control_ids": ids_for(r)} for r in rows])


def main() -> int:
    if (ROOT / "controls/control-catalog.csv").stat().st_size > 2000 and "--force" not in sys.argv:
        print("Refusing to overwrite the curated catalog. The CSV is authoritative since B7 review passes;"
              " rerun with --force only to deliberately reseed (review edits would be lost).")
        return 1
    req_path = ROOT / "regulatory/requirements.csv"
    req_index = {r["req_id"]: r for r in read(req_path)}
    def extend(c):
        reqs = c["requirement_ids"].split(";") + EXTRA_REQS.get(c["control_id"], [])
        pols = c["policy_ids"].split(";") + EXTRA_POLS.get(c["control_id"], [])
        return {**c, "requirement_ids": J(dict.fromkeys(filter(None, reqs))),
                "policy_ids": J(dict.fromkeys(filter(None, pols)))}
    controls = [extend(to_row(c)) for c in C]
    controls = [{**c, "source_ids": sources_for(c["requirement_ids"].split(";"), req_index)} for c in controls]
    missing = sorted({r for c in controls for r in c["requirement_ids"].split(";") if r and r not in req_index})
    if missing:
        print("Unknown requirement ids:", missing)
        return 1
    write(ROOT / "controls/control-catalog.csv", REGISTERS["controls"]["columns"], controls)
    relink(req_path, "requirements", "req_id", reverse(controls, "requirement_ids"))
    pol_map = reverse(controls, "policy_ids")
    # A top-level policy is implemented by the controls of its sections.
    pol_map = {**pol_map, **{
        parent: sorted({c for k, v in pol_map.items() if k.startswith(parent + ".") for c in v} | set(pol_map.get(parent, [])))
        for parent in {k.split(".")[0] for k in pol_map}
    }}
    relink(ROOT / "policies/policy-inventory.csv", "policies", "policy_id", pol_map)
    relink(ROOT / "registers/evidence-types.csv", "evidence_types", "evidence_type_id", reverse(controls, "evidence_type_ids"))
    relink(ROOT / "registers/validation-procedures.csv", "validations", "validation_id", reverse(controls, "validation_ids"))
    print(f"controls: {len(controls)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
