#!/usr/bin/env python3
"""Five-year total cost of ownership model for assurance operating models.

Input:  economics/parameters.csv
        scenario,component,category,y1_low,y1_high,annual_low,annual_high,
        avoidable,evidence_class,source_ids,notes
  - y1_* is the first-year cost (setup + first-year run); annual_* applies to
    years 2..5. All USD, nominal, undiscounted unless --rate is given.
  - avoidable: "no" for unavoidable external costs (e.g. the CPA examination
    itself), "yes" for costs the operating model can reduce or eliminate.
Output: economics/generated/tco-summary.md and tco-summary.csv

Pure computation; I/O only in main. Ranges are carried through as low/high,
never collapsed to a point estimate.
"""

import csv
import sys
from collections import defaultdict
from functools import reduce
from pathlib import Path

ROOT = Path(__file__).resolve().parent
YEARS = 5


def to_float(value: str) -> float:
    return float(value) if value.strip() else 0.0


def parse(rows) -> tuple:
    return tuple(
        {**r, **{k: to_float(r[k]) for k in ("y1_low", "y1_high", "annual_low", "annual_high")}}
        for r in rows
    )


def discount(rate: float, year: int) -> float:
    return 1.0 / ((1.0 + rate) ** (year - 1))


def five_year(row, rate: float) -> tuple:
    later = sum(discount(rate, y) for y in range(2, YEARS + 1))
    return (row["y1_low"] + row["annual_low"] * later,
            row["y1_high"] + row["annual_high"] * later)


def summarise(rows, rate: float) -> dict:
    def add(acc, row):
        low, high = five_year(row, rate)
        key = (row["scenario"], row["avoidable"])
        prev = acc.get(key, (0.0, 0.0))
        return {**acc, key: (prev[0] + low, prev[1] + high)}
    return reduce(add, rows, {})


def by_scenario(summary: dict) -> dict:
    out = defaultdict(lambda: {"no": (0.0, 0.0), "yes": (0.0, 0.0)})
    for (scenario, avoidable), value in summary.items():
        out[scenario][avoidable] = value
    return dict(out)


def render(table: dict, rate: float) -> str:
    fmt = lambda v: f"${v[0]:,.0f} – ${v[1]:,.0f}"
    total = lambda d: (d["no"][0] + d["yes"][0], d["no"][1] + d["yes"][1])
    lines = (
        "# Five-year TCO summary (generated)",
        "",
        f"Generated by `economics/tco_model.py` from `economics/parameters.csv`. Discount rate: {rate:.0%}.",
        "Do not edit by hand. Ranges, not point estimates. See `economics/compliance-economics.md` for interpretation.",
        "",
        "| Scenario | Unavoidable external | Reducible | Total (5 yr) |",
        "|---|---|---|---|",
        *(f"| {s} | {fmt(d['no'])} | {fmt(d['yes'])} | {fmt(total(d))} |" for s, d in sorted(table.items())),
    )
    return "\n".join(lines) + "\n"


def main(argv) -> int:
    rate = float(argv[argv.index("--rate") + 1]) if "--rate" in argv else 0.0
    with (ROOT / "parameters.csv").open(newline="", encoding="utf-8") as handle:
        rows = parse(tuple(csv.DictReader(handle)))
    table = by_scenario(summarise(rows, rate))
    out = ROOT / "generated"
    out.mkdir(exist_ok=True)
    (out / "tco-summary.md").write_text(render(table, rate), encoding="utf-8")
    with (out / "tco-summary.csv").open("w", newline="", encoding="utf-8") as handle:
        writer = csv.writer(handle, lineterminator="\n")
        writer.writerow(("scenario", "unavoidable_low", "unavoidable_high", "reducible_low", "reducible_high"))
        writer.writerows(
            (s, round(d["no"][0]), round(d["no"][1]), round(d["yes"][0]), round(d["yes"][1]))
            for s, d in sorted(table.items())
        )
    print(render(table, rate))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
